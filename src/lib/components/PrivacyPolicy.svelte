<article class="privacy-policy">
	<h1>Privacy Policy</h1>
	<p class="effective">Effective October 13, 2026</p>

	<p class="lead">We collect only what we need to answer you, register you for events, and provide the services you ask for, and we never sell it.</p>

	<h2>Who we are</h2>
	<p>Muslim Legacy Planning is the community education brand of McDaniel Estate Planning, a law practice of Leonard McDaniel, attorney licensed in Texas and California, 13100 Wortham Center Drive, 3rd Floor, Houston, Texas 77065. In this policy, “we” and “us” mean McDaniel Estate Planning.</p>
	<p>This policy covers information collected through muslimlegacyplanning.com, mcdanielestateplanning.com, our free Islamic will tool, our online workshops and webinars, our social media pages and ads, and the forms you complete to contact us or book a consultation.</p>

	<h2>Information we collect</h2>
	<ul>
		<li><strong>Contact details you give us:</strong> your name, email address, phone number, and state, when you register for a workshop, request a consultation, or contact us.</li>
		<li><strong>Workshop registration answers:</strong> how you heard about us and any question you submit in advance.</li>
		<li><strong>Facebook and Instagram lead forms:</strong> when you register through a form inside a Facebook or Instagram ad, Meta sends us the name and email you submit.</li>
		<li><strong>Free Islamic will tool:</strong> the family and estate details you enter so the tool can generate your document, and the email address we send it to.</li>
		<li><strong>Consultation and client information:</strong> information you share when booking or during a consultation, which we treat as described under “No attorney-client relationship” below.</li>
		<li><strong>Basic website data:</strong> pages visited and general device and browser information, collected by our own website systems.</li>
	</ul>

	<h2>How we use it</h2>
	<ul>
		<li>To register you for a workshop and send you the join link, reminders, and the recording.</li>
		<li>To generate and email the documents you request through the free will tool.</li>
		<li>If you use the free will tool, to send a short series of follow-up emails explaining what a will can and cannot do. Every email includes a way to unsubscribe.</li>
		<li>To respond to your questions and schedule consultations you request.</li>
		<li>To learn which outreach channels work, in aggregate, so we can reach more families.</li>
	</ul>
	<p>We do not sell, rent, or trade your personal information.</p>

	<h2>Who we share it with</h2>
	<p>We share information only with service providers that help us run our practice, and only as needed for that purpose:</p>
	<ul>
		<li><strong>Zoom</strong>, to host workshops and manage registration.</li>
		<li><strong>Meta (Facebook and Instagram)</strong>, which collects the information you submit through its lead forms and handles it under its own <a href="https://www.facebook.com/privacy/policy">Data Policy</a>.</li>
		<li><strong>Email, website hosting, scheduling, and practice-management providers</strong>, to store and send your information on our behalf.</li>
	</ul>
	<p>We may also disclose information when the law requires it, or to protect our rights or the safety of others. Partner organizations such as masjids that promote our workshops do not receive your personal information from us unless you ask us to share it.</p>

	<h2>Cookies, tracking, and Do Not Track</h2>
	<p>Our websites do not use third-party advertising pixels or trackers, such as the Meta Pixel. We may use first-party tools and simple tracking links to count visits and see which outreach brought you to us.</p>
	<p>Because we do not track you across other websites, we do not change our practices in response to browser “Do Not Track” signals.</p>

	<h2>No attorney-client relationship</h2>
	<p>Registering for a workshop, using the free will tool, or contacting us does not create an attorney-client relationship. One is formed only when we both sign a written engagement agreement. Until then, please do not send confidential details about your family or finances through web forms, social media, or email.</p>
	<p>Information you share with us as a prospective or current client is handled under our professional duties of confidentiality, in addition to this policy.</p>

	<h2>Security and retention</h2>
	<p>We use reasonable administrative and technical safeguards, including encrypted connections and access limited to people who need it. No system is perfectly secure, and we cannot guarantee absolute security.</p>
	<p>We keep workshop and contact information until you ask us to delete it. If you use the free will tool, we keep the details you enter and your generated document only as long as needed to deliver it and let you download it again, and no longer than 30 days. We keep client files for the periods required by our professional obligations and applicable law.</p>

	<h2>Your choices and rights</h2>
	<p>You can ask us at any time to see the personal information we hold about you, correct it, delete it, or stop sending you emails. Email us at the address below and we will respond within 45 days. Deletion requests do not apply to client files we must keep under our professional obligations.</p>
	<p>California residents may request the categories of personal information we have collected and the categories of third parties we share it with. We do not sell or share personal information for cross-context behavioral advertising.</p>

	<h2>Children</h2>
	<p>Our websites and workshops are intended for adults. We do not knowingly collect personal information from children under 13.</p>

	<h2>Changes to this policy</h2>
	<p>We may update this policy from time to time. The effective date at the top of this page shows when it last changed.</p>

